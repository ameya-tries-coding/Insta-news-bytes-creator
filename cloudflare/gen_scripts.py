"""Copy the page-cleaning scripts from ../shot.py into src/page-scripts.js so the
laptop version and the Cloudflare version capture headlines the same way."""
import json, sys
from pathlib import Path
here = Path(__file__).resolve().parent
sys.path.insert(0, str(here.parent))
import shot  # noqa: E402
out = ["// Generated by gen_scripts.py from shot.py. Do not edit by hand."]
for name in ("CLEAN_JS", "NO_IMAGES_JS", "FIND_JS", "RECT_JS"):
    out.append(f"export const {name} = {json.dumps(getattr(shot, name).strip())};")
(here / "src" / "page-scripts.js").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote src/page-scripts.js")
